-- 1. ESQUEMAS -------------------------------------------------------------
create schema if not exists bronze;
create schema if not exists silver;
create schema if not exists gold;
create schema if not exists meta;

-- Permisos para el cliente supabase-py (usa el rol anon con la anon key)
grant usage on schema bronze, silver, gold, meta to anon, authenticated, service_role;
alter default privileges in schema bronze, silver, gold, meta
  grant all on tables to anon, authenticated, service_role;

-- 2. CAPA BRONZE: carga inmutable del CSV crudo ---------------------------
create table if not exists bronze.citas_raw (
  id             bigint generated by default as identity primary key,
  patientid      numeric,            -- numeric: el CSV trae PatientId como float
  appointmentid  bigint,
  gender         text,
  scheduledday   text,               -- texto crudo ISO, sin transformar (inmutabilidad)
  appointmentday text,
  age            integer,
  neighbourhood  text,
  scholarship    integer,
  hipertension   integer,
  diabetes       integer,
  alcoholism     integer,
  handcap        integer,
  sms_received   integer,
  no_show        text,
  fuente_archivo text,
  created_at     timestamptz default now() not null
);

-- 3. CAPA SILVER: datos limpios y con ingeniería de características -------
create table if not exists silver.citas_cleaned (
  id                     bigint generated by default as identity primary key,
  patient_id             bigint,
  appointment_id         bigint,
  gender                 text,
  scheduled_day          text,        -- 'YYYY-MM-DD HH:MM:SS'
  appointment_day        text,
  lead_time              integer,
  age                    integer,
  grupo_edad             text,        -- Niño | Joven | Adulto | Adulto Mayor
  neighbourhood          text,
  scholarship            integer,
  hipertension           integer,
  diabetes               integer,
  alcoholism             integer,
  handcap                integer,
  sms_received           integer,
  historical_noshows     integer,     -- acumulado sin data leakage
  no_show_target         integer,     -- 1 = faltó, 0 = asistió
  alerta_calidad_logica  boolean,
  fuente_archivo         text,
  created_at             timestamptz default now() not null
);

create index if not exists idx_silver_patient_id  on silver.citas_cleaned (patient_id);
create index if not exists idx_silver_appointment on silver.citas_cleaned (appointment_id);

-- 4. CAPA GOLD: tablas MLOps ----------------------------------------------
-- 4a. Dataset de entrenamiento (poblado por 03_compare_train_models.py)
create table if not exists gold.ml_train_dataset (
  id                  bigint generated by default as identity primary key,
  appointment_id      bigint,
  lead_time           integer,
  age                 integer,
  scholarship         integer,
  hipertension        integer,
  diabetes            integer,
  alcoholism          integer,
  handcap             integer,
  sms_received        integer,
  historical_noshows  integer,
  no_show_target      integer,
  created_at          timestamptz default now() not null
);

-- 4b. Entrada para inferencia batch (poblado por 04_predict_scoring.py)
create table if not exists gold.score_input (
  id                  bigint generated by default as identity primary key,
  appointment_id      bigint,
  patient_id          bigint,
  scheduled_day       text,
  appointment_day     text,
  lead_time           integer,
  age                 integer,
  scholarship         integer,
  hipertension        integer,
  diabetes            integer,
  alcoholism          integer,
  handcap             integer,
  sms_received        integer,
  historical_noshows  integer,
  created_at          timestamptz default now() not null
);

-- 4c. Salida de predicciones (riesgo + acción recomendada)
create table if not exists gold.score_output (
  id                   bigint generated by default as identity primary key,
  appointment_id       bigint,
  patient_id           bigint,
  probability_noshow   double precision,
  risk_level           text,        -- 🔴/🟡/🟢 nivel de riesgo
  recommended_action   text,
  created_at           timestamptz default now() not null
);

-- 4d. Feedback post-consulta (registro de atención desde la app)
create table if not exists gold.feedback_loop (
  id                   bigint generated by default as identity primary key,
  appointment_id       bigint,
  actual_duration_min  integer,
  satisfaction_score   integer,     -- 1 a 5
  rescheduled_status   text,
  created_at           timestamptz default now() not null
);

-- 5. META: auditoría de procesos ETL --------------------------------------
create table if not exists meta.log_procesos (
  id                   bigint generated by default as identity primary key,
  proceso_nombre       text,
  capa_destino         text,        -- BRONZE | SILVER | GOLD
  registros_procesados integer,
  estado               text,        -- INICIADO | EXITOSO | ERROR
  mensaje_error        text,
  usuario_ejecutor     text,
  fecha_ejecucion      timestamptz default now() not null
);

-- 6. CAPA GOLD ANALÍTICA: MODELO ESTRELLA (puntos 1, 6, 7, 9 y 11 del CPP1)
-- Dimensiones conformes (dim_barrio, dim_paciente, dim_tiempo) y tabla de
-- hechos transaccional (fact_citas), pobladas por src/05_build_star_schema.py
-- --------------------------------------------------------------------------

-- 6a. Dimensión Barrio
create table if not exists gold.dim_barrio (
  id_barrio     integer generated by default as identity primary key,
  nombre_barrio text not null unique
);

-- 6b. Dimensión Paciente (usa el id natural del dataset + aggregates históricos)
create table if not exists gold.dim_paciente (
  id_paciente    bigint primary key,
  primera_cita   date,
  ultima_cita    date,
  total_citas    integer default 0,
  total_noshows  integer default 0
);

-- 6c. Dimensión Tiempo (id = formato YYYYMMDD)
create table if not exists gold.dim_tiempo (
  id_tiempo      integer primary key,
  fecha          date not null unique,
  anio           integer,
  mes            integer,
  trimestre      integer,
  dia_semana     text,
  es_fin_semana  boolean
);

-- 6d. Tabla de hechos transaccional (una fila por cita)
create table if not exists gold.fact_citas (
  id                  bigint generated by default as identity primary key,
  appointment_id      bigint not null unique,
  id_paciente         bigint references gold.dim_paciente (id_paciente),
  id_barrio           integer references gold.dim_barrio (id_barrio),
  id_tiempo           integer references gold.dim_tiempo (id_tiempo),
  genero              text,
  edad                integer,
  lead_time           integer,
  scholarship         integer,
  hipertension        integer,
  diabetes            integer,
  alcoholism          integer,
  handcap             integer,
  sms_received        integer,
  historical_noshows  integer,
  no_show_target      integer,
  created_at          timestamptz default now() not null
);

create index if not exists idx_fact_paciente on gold.fact_citas (id_paciente);
create index if not exists idx_fact_barrio   on gold.fact_citas (id_barrio);
create index if not exists idx_fact_tiempo   on gold.fact_citas (id_tiempo);

-- 7. RLS: habilitado con políticas permisivas (proyecto académico) --------
-- Se aplica AL FINAL para garantizar que todas las tablas ya existen.
alter table bronze.citas_raw        enable row level security;
alter table silver.citas_cleaned    enable row level security;
alter table gold.ml_train_dataset   enable row level security;
alter table gold.score_input        enable row level security;
alter table gold.score_output       enable row level security;
alter table gold.feedback_loop      enable row level security;
alter table meta.log_procesos       enable row level security;
alter table gold.dim_barrio         enable row level security;
alter table gold.dim_paciente       enable row level security;
alter table gold.dim_tiempo         enable row level security;
alter table gold.fact_citas         enable row level security;

do $$
declare t text;
begin
  foreach t in array array[
    'bronze.citas_raw', 'silver.citas_cleaned', 'gold.ml_train_dataset',
    'gold.score_input', 'gold.score_output', 'gold.feedback_loop', 'meta.log_procesos',
    'gold.dim_barrio', 'gold.dim_paciente', 'gold.dim_tiempo', 'gold.fact_citas'
  ] loop
    execute format('drop policy if exists acceso_total_anon on %s', t);
    execute format(
      'create policy acceso_total_anon on %s for all to anon, authenticated using (true) with check (true)', t
    );
  end loop;
end $$;

-- 8. Grants explícitos sobre todas las tablas creadas ----------------------
grant all on all tables in schema bronze, silver, gold, meta to anon, authenticated, service_role;
